// The coordinators tree's lines, drawn like a git graph: a trunk from each coordinator, one connector
// from the line above into each chat's ring, and the chat's state on its ring. Pure: a row's role in,
// inline SVG out. Each row draws only its own height (plus the 1px gap below it), so rows join at any
// height with no gap or overlap: panel.css draws the straight runs (the line a row hangs from, a
// lead's line down, the trunk passing workers) from the row's edges, and the SVG here, anchored at
// the row's middle, draws the connector, the ring and the PR bead in px around the character.
//
// Row coordinates: x from the row's left edge (rows start 6 px left of the coordinator's
// character), y from the middle of the character's body. Colors come from panel.css variables:
// --own-c (this row's branch), --lane-c (its lead's), --trunk-c, --rowbg.

/**
 * What a chat's ring says: working (a shimmer travels around it), monitoring (slower, dimmer, on a
 * dashed ring), asking, done (still in flight), finished, sleeping.
 */

/** The states whose ring carries a travelling shimmer instead of the character's spinning badge. */
export const BEAMS                       = ['working', 'monitoring']


/** The tree's geometry, in px. panel.css repeats these (--tx, --X1, --X2): keep them in step. */
export const GEO = {
  /** A row starts this far left of the coordinator's character. */
  edge: 6,
  /** The middle of a 28 px coordinator character with its badge frame, and without (asleep). */
  tx: 13.1,
  txIdle: 14,
  /** Where a lead's and a worker's 20 px character starts in the row, and its middle within it. */
  av1: 33.75,
  av2: 57.75,
  ax: 9.355
}
const X1 = GEO.av1 + GEO.ax
export const nodeX = (depth        ) => Math.round((X1 + Math.max(0, depth) * (GEO.av2 - GEO.av1)) * 1000) / 1000
/** The trunk's x in a row (and in the coordinator's own row, which starts at the same edge). */
export const trunkX = (asleep         ) => GEO.edge + (asleep ? GEO.txIdle : GEO.tx)

const n = (v        ) => String(Math.round(v * 100) / 100)
const svg = (cls        , body        ) => `<svg class="${cls}" aria-hidden="true">${body}</svg>`

/** One row's place in the tree. */











/** A chat's ring around its character, and where its one connector leaves the line above. */
const RING = 12, FORK = 11

function ring(cx        , r        , node           , ask          )         {
  return `<circle class="node n-${node}${node === 'asking' ? ` k-${ask ?? 'question'}` : ''}" cx="${n(cx)}" cy="0" r="${r}" pathLength="100"/>`
}

/** A chat row's connector, ring and (for a lead) PR bead. */
export function rowLines({ nested, depth = nested ? 1 : 0, trunk, node, ask, cap }         )         {
  const x = nodeX(depth), from = depth > 0 ? nodeX(depth - 1) : trunk, edge = x - RING
  // One connector per chat, from the line it hangs from into its ring; a finished chat's dims.
  const fork = `<path class="fork" d="M${n(from)} ${-FORK}C${n(from)} ${n(-FORK * 0.35)} ${n(from + (edge - from) * 0.35)} 0 ${n(edge)} 0"/>`
  // The lead's PR sits on its ring at the lower left, opposite the character's own badge.
  const bead = !nested && cap ? `<g class="tl-cap" transform="translate(${n(x - RING * Math.SQRT1_2)} ${n(RING * Math.SQRT1_2)})">${CAP[cap]}</g>` : ''
  return svg('tl-c', fork + ring(x, RING, node, ask) + bead)
}

/** The coordinator's ring, where its trunk starts. */
export const headLines = (trunk        , node           , ask          ) => svg('tl-h', ring(trunk, 16, node, ask))

/** A lead's PR as a bead: open (a ring in its checks' color), merged, failing, closed, draft. */
export function capGlyph(pr                                                 )                {
  if (!pr) return null
  if (pr.state === 'merged') return 'merged'
  if (pr.state === 'closed') return 'closed'
  if (pr.state === 'draft') return 'draft'
  return pr.checks === 'failure' ? 'failing' : pr.checks === 'pending' ? 'pending' : 'open'
}
const CAP                         = {
  open: '<circle class="cap c-open" r="3.25"/>',
  pending: '<circle class="cap c-pending" r="3.25"/>',
  merged: '<circle class="cap c-merged" r="3.75"/>',
  failing: '<circle class="cap c-failing" r="3.75"/><path class="cap-x" d="M-1.5 -1.5l3 3M1.5 -1.5l-3 3"/>',
  closed: '<circle class="cap c-closed" r="3.25"/><path class="cap-x" d="M-1.6 1.6l3.2 -3.2"/>',
  draft: '<circle class="cap c-draft" r="3.25" pathLength="12"/>'
}
